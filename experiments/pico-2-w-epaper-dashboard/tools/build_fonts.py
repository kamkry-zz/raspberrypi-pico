#!/usr/bin/env python3
"""Generate the bitmap fonts used by the dashboard.

Requires Pillow (only for regenerating the fonts; the runtime uses the
generated Python modules).  Run from the experiment root:

    python3 tools/build_fonts.py

The source font is IBM Plex Mono, licensed under the SIL Open Font License 1.1.
See tools/fonts/OFL.txt.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "tools" / "fonts"
OUT_DIR = ROOT / "lib"

CHARS = (
    " "
    + "".join(chr(code) for code in range(0x21, 0x7F))
    + "ąćęłńóśźżĄĆĘŁŃÓŚŹŻ°·–—…×"
)

# The large font is only used for numbers, temperatures and 400x300.
# Keeping it a subset saves roughly 20 KB of module/heap on the Pico.
CHARS_LARGE = " 0123456789,%-°C×"

# name, ttf, pixel size, threshold, characters
SPECS = [
    ("small", "IBMPlexMono-Regular.ttf", 11, 80, CHARS),
    ("medium", "IBMPlexMono-SemiBold.ttf", 14, 128, CHARS),
    ("large", "IBMPlexMono-SemiBold.ttf", 24, 128, CHARS_LARGE),
]


def pack_glyph(image, width, height):
    pixels = image.load()
    bytes_per_row = (width + 7) // 8
    out = bytearray(height * bytes_per_row)
    for y in range(height):
        base = y * bytes_per_row
        for x in range(width):
            if pixels[x, y]:
                out[base + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(out)


def build(name, ttf_name, size, threshold, chars):
    path = FONT_DIR / ttf_name
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    advance = max(1, int(round(font.getlength("M"))))
    height = ascent + descent
    if height < 1 or advance < 1:
        raise RuntimeError("bad font metrics for %s" % name)

    # Render on a common grid first, then crop the union of all ink so the
    # bitmap does not carry the font's internal leading.  This keeps the
    # dashboard compact and preserves the relative baseline.
    raw = []
    min_y = height
    max_y = -1
    for char in chars:
        image = Image.new("L", (advance, height), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0, 0), char, font=font, fill=255)
        raw.append(image)
        bbox = image.getbbox()
        if bbox:
            min_y = min(min_y, bbox[1])
            max_y = max(max_y, bbox[3])
    if max_y < 0:
        min_y, max_y = 0, height
    top = max(0, min_y - 1)
    bottom = min(height, max_y + 1)
    height = max(1, bottom - top)

    glyphs = {}
    for char, image in zip(chars, raw):
        image = image.crop((0, top, advance, bottom))
        # Threshold to a crisp 1-bit bitmap.
        image = image.point(lambda value: 255 if value >= threshold else 0, mode="1")
        glyphs[ord(char)] = pack_glyph(image.convert("L"), advance, height)

    lines = [
        "# Generated by tools/build_fonts.py from IBM Plex Mono (OFL 1.1).",
        "# Do not edit by hand.",
        "from canvas import Font",
        "",
        "WIDTH = %d" % advance,
        "HEIGHT = %d" % height,
        "ADVANCE = %d" % advance,
        "",
        "GLYPHS = {",
    ]
    for code in sorted(glyphs):
        lines.append("    %d: %r," % (code, glyphs[code]))
    lines += [
        "}",
        "",
        "FONT = Font(WIDTH, HEIGHT, ADVANCE, GLYPHS)",
        "",
    ]
    out_path = OUT_DIR / ("font_%s.py" % name)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(
        "%s: %dx%d, advance %d, %d glyphs -> %s"
        % (name, advance, height, advance, len(glyphs), out_path.name)
    )


def main():
    for spec in SPECS:
        build(*spec)


if __name__ == "__main__":
    main()
